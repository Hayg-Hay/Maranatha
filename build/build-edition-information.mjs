import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import catalog from './edition-information-catalog.mjs';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const source = read('app.js').match(/const TRANSLATIONS = (\[[\s\S]*?\n  \]);/);
if (!source) throw new Error('Translation registry could not be read; update the metadata builder explicitly.');
const editions = [...vm.runInNewContext(source[1]), { id: 'lxx-swete', label: 'Septuagint (Swete, 1905)', src: 'data/lxx-swete.js' }];
if (editions.length !== Object.keys(catalog).length) throw new Error('Edition information catalog must cover the complete registry and native LXX.');
const context = { window: {} }; vm.runInNewContext(read('data/canon.js'), context);
const canon = context.window.MARANATHA_CANON;
const result = {};
for (const t of editions) {
  const note = catalog[t.id]; if (!note?.verification || !note.evidence?.length) throw new Error(`Missing evidence summary: ${t.id}`);
  for (const file of note.evidence) if (!fs.existsSync(path.join(root, file))) throw new Error(`Missing evidence file: ${file}`);
  vm.runInNewContext(read(t.src.split('?')[0]), context);
  const data = context.window.MARANATHA_TRANSLATIONS[t.id];
  const native = t.id === 'lxx-swete';
  const ids = native ? data.books.map(book => book.id) : Object.keys(data.books);
  const count = testament => ids.filter(id => canon.books.find(book => book.id === id)?.testament === testament).length;
  const coverage = native ? `${ids.length} native books/components; Septuagint Old Testament, no New Testament.`
    : `${ids.length} books: ${count('OT')} Old Testament, ${count('NT')} New Testament. Coverage describes this imported dataset, not all editions of the translation.`;
  const terms = note.terms || (typeof data.license === 'string' ? data.license : 'Reuse terms are not recorded in this panel; consult the retained source evidence.');
  result[t.id] = {
    label: t.label,
    description: t.description || data.description || data.source || 'See edition provenance and retained evidence below.',
    provenance: [data.sourceEdition || t.label, data.sourcePublisher, data.source].filter(Boolean).join('\n'),
    coverage,
    terms: [data.copyright, terms, typeof data.license === 'object' ? data.license?.attribution : null].filter(Boolean).join('\n'),
    limitations: [...new Set([note.limitation, data.editionUncertainty, t.note, data.nativeVersification ? 'Read in independent source numbering; same-numbered rows are not a verified cross-edition alignment.' : native ? null : 'References follow the imported dataset; equal numbers alone are not proof of textual correspondence.'].filter(Boolean))].join('\n'),
    verification: note.verification,
    warningKind: t.note ? note.audit ? 'audit' : 'limitations' : null,
    warning: t.note || null,
    links: [...note.evidence.map((href, index) => ({ href, label: index === 0 ? 'Project source and verification record' : `Supporting evidence: ${path.basename(href)}` })), ...[data.sourceUrl, data.sourceLicenceUrl].filter(Boolean).map(href => ({ href, label: href === data.sourceLicenceUrl ? 'Distributor licence notice (online)' : 'Source edition (online)' }))],
  };
}
const output = '// Generated by build/build-edition-information.mjs; metadata only, no Scripture.\nwindow.MARANATHA_EDITION_INFORMATION_DATA = ' + JSON.stringify(result, null, 2) + ';\n';
const target = path.join(root, 'data/edition-information.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== output) throw new Error('Edition information is stale. Run node build/build-edition-information.mjs.');
  console.log(`PASS ${editions.length} edition records match retained metadata and evidence summaries.`);
} else { fs.writeFileSync(target, output); console.log(`Built ${editions.length} metadata-only edition records (${Buffer.byteLength(output)} bytes).`); }
